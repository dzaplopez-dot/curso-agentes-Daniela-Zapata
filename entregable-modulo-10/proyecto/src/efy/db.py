import sqlite3

from . import config

try:
    import psycopg
    from psycopg.rows import dict_row
except ImportError:
    psycopg = None
    dict_row = None


def esquema(dialecto="sqlite"):
    if dialecto == "postgres":
        pk = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        fecha = "TIMESTAMPTZ NOT NULL"
    else:
        pk = "INTEGER PRIMARY KEY AUTOINCREMENT"
        fecha = "TEXT NOT NULL"
    return f"""
CREATE TABLE IF NOT EXISTS perfumes (
    codigo         TEXT PRIMARY KEY,
    inspirado_en   TEXT NOT NULL,
    casa           TEXT NOT NULL,
    genero         TEXT NOT NULL CHECK (genero IN ('F', 'M', 'U')),
    familia_raw    TEXT,
    familia_base   TEXT NOT NULL,
    ml             INTEGER NOT NULL DEFAULT 100,
    precio         NUMERIC(12, 2) NOT NULL DEFAULT 40000,
    stock          INTEGER NOT NULL DEFAULT 0,
    activo         INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS pedidos (
    id          {pk},
    chat_id     TEXT NOT NULL,
    codigo      TEXT NOT NULL REFERENCES perfumes(codigo),
    cantidad    INTEGER NOT NULL DEFAULT 1,
    estado      TEXT NOT NULL DEFAULT 'borrador'
                CHECK (estado IN ('borrador', 'confirmado', 'cancelado')),
    msg_id      TEXT NOT NULL,
    creado_en   {fecha},
    UNIQUE (chat_id, msg_id)
);

CREATE TABLE IF NOT EXISTS sesiones (
    chat_id        TEXT PRIMARY KEY,
    pedido_id      BIGINT,
    actualizado_en {fecha}
);
"""


class Conexion:
    def __init__(self, crudo, dialecto):
        self.crudo = crudo
        self.dialecto = dialecto

    def sentencia(self, sql):
        if self.dialecto == "postgres":
            return sql.replace("?", "%s")
        return sql

    def execute(self, sql, params=()):
        cursor = self.crudo.cursor()
        cursor.execute(self.sentencia(sql), tuple(params))
        return cursor

    def executescript(self, sql):
        if self.dialecto == "sqlite":
            self.crudo.executescript(sql)
            return
        cursor = self.crudo.cursor()
        for bloque in sql.split(";"):
            if bloque.strip():
                cursor.execute(bloque)

    def commit(self):
        self.crudo.commit()

    def rollback(self):
        self.crudo.rollback()

    def close(self):
        self.crudo.close()

    def __enter__(self):
        return self

    def __exit__(self, tipo, valor, traza):
        if tipo is None:
            self.crudo.commit()
        else:
            self.crudo.rollback()
        self.crudo.close()
        return False


def conectar():
    if config.BACKEND == "postgres":
        if psycopg is None:
            raise RuntimeError("psycopg no está instalado: pip install 'psycopg[binary]'")
        if not config.DATABASE_URL:
            raise RuntimeError("Falta DATABASE_URL para el backend postgres")
        crudo = psycopg.connect(config.DATABASE_URL, row_factory=dict_row)
        return Conexion(crudo, "postgres")
    config.DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    crudo = sqlite3.connect(config.DB_PATH)
    crudo.row_factory = sqlite3.Row
    crudo.execute("PRAGMA foreign_keys = ON")
    return Conexion(crudo, "sqlite")


def inicializar():
    with conectar() as con:
        con.executescript(esquema(con.dialecto))
    if config.BACKEND == "postgres":
        return config.DATABASE_URL
    return config.DB_PATH


def error_db():
    if config.BACKEND == "postgres":
        return (RuntimeError, psycopg.Error) if psycopg else (RuntimeError,)
    return (sqlite3.Error,)


def error_integridad():
    if config.BACKEND == "postgres" and psycopg is not None:
        return (psycopg.errors.UniqueViolation,)
    return (sqlite3.IntegrityError,)


def dialecto_actual():
    return "postgres" if config.BACKEND == "postgres" else "sqlite"
