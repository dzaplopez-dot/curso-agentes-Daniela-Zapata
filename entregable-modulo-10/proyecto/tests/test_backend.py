from efy import db


def test_sentencias_se_traducen_para_postgres():
    con = db.Conexion(None, "postgres")
    assert con.sentencia("SELECT * FROM perfumes WHERE codigo = ?") == (
        "SELECT * FROM perfumes WHERE codigo = %s"
    )
    assert con.sentencia("SELECT 1") == "SELECT 1"


def test_sentencias_sqlite_no_cambian():
    con = db.Conexion(None, "sqlite")
    sql = "SELECT * FROM perfumes WHERE codigo = ?"
    assert con.sentencia(sql) == sql


def test_esquema_postgres_usa_identidad_y_timestamptz():
    esquema = db.esquema("postgres")
    assert "GENERATED BY DEFAULT AS IDENTITY" in esquema
    assert "TIMESTAMPTZ" in esquema
    assert "UNIQUE (chat_id, msg_id)" in esquema


def test_esquema_sqlite_usa_autoincrement():
    esquema = db.esquema("sqlite")
    assert "AUTOINCREMENT" in esquema
    assert "TIMESTAMPTZ" not in esquema
